from lib import hashing, local_llm
from services.render.render_service import RenderService
from services.tts import kokoro_client

# Keep strong refs to in-flight render tasks so they aren't garbage-collected.
_RENDER_TASKS: Set[asyncio.Task] = set()


def _probe_worker(url: str) -> bool:
    try:
        r = httpx.get(f"{url}/api/render/health", timeout=1.5)
        return r.is_success or r.status_code in (404, 405)
    except Exception:  # noqa: BLE001
        return False


def setup_render_routes(render_service: RenderService) -> APIRouter:
    router = APIRouter(prefix="/api/trend-vault", tags=["render"])

    @router.post("/render")
    async def render(request: Request):
        body = await request.json()
        settings = body.get("settings")
        script_lines = body.get("scriptLines")

        errors = []
        if not settings:
            errors.append("settings missing")
        if not isinstance(script_lines, list) or not script_lines:
            errors.append("scriptLines: at least one line required")
        elif any(not (l.get("text") or "").strip() for l in script_lines):
            errors.append("scriptLines: empty line text — remove blank lines")
        if settings:
            if not settings.get("trendVaultSign"):
                errors.append("trendVaultSign missing")
            ds = settings.get("durationSeconds")
            if settings.get("durationMode") == "fixed" and not (isinstance(ds, (int, float)) and ds > 0):
                errors.append("durationMode=fixed but durationSeconds invalid")
            pt = settings.get("previewTiming")
            if pt:
                submitted_script_hash = hashing.stable_hash(
                    "||".join((l.get("text") or "").strip() for l in script_lines))
                v = settings.get("voice") or {}
                submitted_engine = ("fish-speech-s2-pro"
                                    if hashing.is_fish_engine(v.get("presetId"), v.get("engine"))
                                    else "kokoro")
                submitted_voice_hash = hashing.voice_hash(v, submitted_engine)
                if pt.get("scriptHash") and pt["scriptHash"] != submitted_script_hash:
                    errors.append("script changed since preview was generated — regenerate the voice preview")
                if pt.get("voiceHash") and pt["voiceHash"] != submitted_voice_hash:
                    errors.append("voice/provider changed since preview — regenerate the voice preview")
                if pt.get("audioPath") and not os.path.exists(pt["audioPath"]):
                    errors.append(f"preview audio file missing on disk: {pt['audioPath']}")
                prov = pt.get("provider")
                if prov and prov not in ("kokoro", "fish-speech-s2-pro") and not re.search(r"kokoro|fish", prov, re.I):
                    errors.append(f"timeline audio was generated by {prov} which is no longer "
                                  "supported — regenerate the voice preview")
        if errors:
            return JSONResponse({"error": "Preflight validation failed", "errors": errors},
                                status_code=400)

        job_id = str(int(time.time() * 1000))
        sign = settings["trendVaultSign"]
        today = datetime.now(timezone.utc).date().isoformat()
        folder = f"{today}_{re.sub(r'\\s+', '_', sign)}_{job_id}"

        os.makedirs(TREND_VAULT_OUT, exist_ok=True)
        job_file = os.path.join(TREND_VAULT_OUT, f"job_{job_id}.json")
        with open(job_file, "w", encoding="utf-8") as f:
            json.dump({"jobId": job_id, "outputFolder": folder,
                       "scriptLines": script_lines, "settings": settings}, f)

        get_job_registry().create(job_id, folder)
        task = asyncio.create_task(
            render_service.run(job_id, folder, script_lines, settings, job_file))
        _RENDER_TASKS.add(task)
        task.add_done_callback(_RENDER_TASKS.discard)

        return {"ok": True, "jobId": job_id, "folder": folder}

    @router.get("/render-status/{job_id}")
    async def render_status(job_id: str):
        reg = get_job_registry()

        async def gen():
            st = reg.get(job_id)
            if not st:
                yield "data: " + json.dumps({"log": "unknown job", "done": True, "success": False}) + "\n\n"
                return
            # Replay history so a late/reconnecting client gets full context.
            for line in list(st.logs):
                yield "data: " + json.dumps({"log": line}) + "\n\n"
            yield "data: " + json.dumps({"progress": st.pct, "stage": st.stage}) + "\n\n"
            if st.status != "running":
                yield "data: " + json.dumps({"done": True, "success": st.success,
                                             "outputFile": st.output_file, "error": st.error}) + "\n\n"
                return
            q = reg.subscribe(job_id)
            try:
                while True:
                    try:
                        ev = await asyncio.wait_for(q.get(), timeout=15)
                    except asyncio.TimeoutError:
                        yield ": ping\n\n"
                        continue
                    yield "data: " + json.dumps(ev) + "\n\n"
                    if ev.get("done"):
                        break
            finally:
                reg.unsubscribe(job_id, q)

        return StreamingResponse(gen(), media_type="text/event-stream", headers={
            "Cache-Control": "no-cache", "Connection": "keep-alive", "X-Accel-Buffering": "no",
        })

    @router.get("/outputs")
    async def outputs():
        return await asyncio.to_thread(render_service.list_outputs)

    @router.delete("/outputs/{folder}")
    async def delete_output(folder: str):
        if not folder or re.search(r"[./\\]", folder):
            return JSONResponse({"error": "Invalid folder name"}, status_code=400)
        target = os.path.join(TREND_VAULT_OUT, folder)
        if not os.path.abspath(target).startswith(os.path.abspath(TREND_VAULT_OUT)):
            return JSONResponse({"error": "Invalid path"}, status_code=400)
        try:
            if os.path.isdir(target):
                shutil.rmtree(target, ignore_errors=True)
            return {"ok": True}
        except Exception as e:  # noqa: BLE001
            return JSONResponse({"error": str(e)}, status_code=500)

    @router.get("/engine-status")
    async def engine_status():
        reachable = await asyncio.to_thread(kokoro_client.probe_reachable)
        local_tts = {"ok": reachable, "engine": "kokoro", "url": kokoro_client._base_url()}
        worker_url = (config.render_worker_url or "").strip()
        worker_online = (await asyncio.to_thread(_probe_worker, worker_url)) if worker_url else False
        llm_reachable = await asyncio.to_thread(local_llm.probe_reachable)
        return {
            "localTts": local_tts,
            "capcut": {"ok": False, "url": os.getenv("CAPCUT_API_URL", "http://localhost:9001")},
            "workerOnline": worker_online, "workerUrl": worker_url,
            "localLlm": {"ok": llm_reachable, "url": config.local_llm_url,
                         "model": config.local_llm_model},
            "localLlmModel": config.local_llm_model,
            "provider": "local",
            "hasAssemblyai": bool(config.assemblyai_api_key),
            "hasPexels": bool(config.pexels_api_key),
        }

    return router
