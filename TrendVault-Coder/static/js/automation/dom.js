const ALPHABET = '0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz';
/** URL-safe random id (replacement for the `nanoid` package). */
export function nanoid(size = 8) {
  let id = '';
  const rnd = (typeof crypto !== 'undefined' && crypto.getRandomValues)
    ? crypto.getRandomValues(new Uint8Array(size))
    : Array.from({ length: size }, () => Math.floor(Math.random() * 256));
  for (let i = 0; i < size; i++) id += ALPHABET[rnd[i] % ALPHABET.length];
  return id;
}

/* ------------------------------------------------------------------ */
/* Bezier edge path (ported from @xyflow/react getBezierPath)          */
/* ------------------------------------------------------------------ */

function controlOffset(distance, curvature) {
  if (distance >= 0) return 0.5 * distance;
  return curvature * 25 * Math.sqrt(-distance);
}

/**
 * Cubic-bezier path for a Right→Left connection (source handle on the right,
 * target handle on the left). Returns { path, labelX, labelY }.
 */
export function getBezierPath(sourceX, sourceY, targetX, targetY, curvature = 0.25) {
  const sourceControlX = sourceX + controlOffset(targetX - sourceX, curvature);
  const targetControlX = targetX - controlOffset(targetX - sourceX, curvature);
  const path = `M${sourceX},${sourceY} C${sourceControlX},${sourceY} ${targetControlX},${targetY} ${targetX},${targetY}`;
  // Midpoint (t = 0.5) of the cubic for label placement.
  const labelX =
    0.125 * sourceX + 0.375 * sourceControlX + 0.375 * targetControlX + 0.125 * targetX;
  const labelY = 0.5 * sourceY + 0.5 * targetY;
  return { path, labelX, labelY };
}

