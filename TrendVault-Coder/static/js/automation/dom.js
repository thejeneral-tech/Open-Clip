/**
 * Automation Map — DOM + drawing helpers.
 *
 * Small framework-free utilities shared by every Automation Map module:
 *  - `el()` / `svg()` element builders
 *  - `icon()` inline-SVG set (replaces the React app's lucide-react icons)
 *  - `getBezierPath()` (ported from React Flow's edge math)
 *  - `nanoid()` id generator (replaces the `nanoid` dependency)
 *
 * Everything here is theme-agnostic; colors come from CSS (TrendVault vars).
 */

/* ------------------------------------------------------------------ */
/* Element builders                                                     */
/* ------------------------------------------------------------------ */

function applyProps(node, props) {
  for (const [k, v] of Object.entries(props || {})) {
    if (v == null || v === false) continue;
    if (k === 'class' || k === 'className') node.className = v;
    else if (k === 'html') node.innerHTML = v;
    else if (k === 'text') node.textContent = v;
    else if (k === 'style' && typeof v === 'object') Object.assign(node.style, v);
    else if (k === 'dataset' && typeof v === 'object') Object.assign(node.dataset, v);
    else if (k.startsWith('on') && typeof v === 'function') {
      node.addEventListener(k.slice(2).toLowerCase(), v);
    } else if (v === true) node.setAttribute(k, '');
    else node.setAttribute(k, v);
  }
}

function appendKids(node, kids) {
  for (const child of kids.flat(Infinity)) {
    if (child == null || child === false) continue;
    node.appendChild(child.nodeType ? child : document.createTextNode(String(child)));
  }
}

/** Build an HTML element. `el('div', {class:'x', onclick}, child1, child2)`. */
export function el(tag, props, ...children) {
  const node = document.createElement(tag);
  applyProps(node, props);
  appendKids(node, children);
  return node;
}

const SVG_NS = 'http://www.w3.org/2000/svg';
/** Build an SVG element (namespaced). */
export function svg(tag, props, ...children) {
  const node = document.createElementNS(SVG_NS, tag);
  for (const [k, v] of Object.entries(props || {})) {
    if (v == null || v === false) continue;
    if (k === 'class') node.setAttribute('class', v);
    else if (k === 'html') node.innerHTML = v;
    else if (k.startsWith('on') && typeof v === 'function') {
      node.addEventListener(k.slice(2).toLowerCase(), v);
    } else node.setAttribute(k, v);
  }
  appendKids(node, children);
  return node;
}

/** Remove all children of a node. */
export function clear(node) {
  while (node.firstChild) node.removeChild(node.firstChild);
  return node;
}

/** Conditional class-name join: cx('a', cond && 'b'). */
export function cx(...args) {
  return args.flat(Infinity).filter(Boolean).join(' ');
}

