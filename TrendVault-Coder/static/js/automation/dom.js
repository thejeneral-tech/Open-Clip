/** Inline-SVG markup for `name`. `extra` lets callers add attrs/inline style. */
export function icon(name, size = 16, extra = '') {
  const inner = ICON_PATHS[name] || '';
  return `<svg width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" ${extra}>${inner}</svg>`;
}

/** An <span> wrapping an icon, for places that need an element. */
export function iconEl(name, size = 16, className = '') {
  return el('span', { class: cx('am-ico', className), html: icon(name, size) });
}
